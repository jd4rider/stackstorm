export function boxSize(id: PieceId): number {
  return BOX[id]
}

export function spawnX(id: PieceId): number {
  // Standard SRS spawn columns: I and O sit one cell further right than JLSTZ.
  return id === 'O' ? 4 : 3
}

export function spawnY(): number {
  return 0
}

export function shapeCells(id: PieceId, rotation: Rotation): Cell[] {
  return SHAPES[id][rotation]
}

export function kicksFor(id: PieceId, from: Rotation, to: Rotation): Cell[] {
  if (id === 'O') return [{ x: 0, y: 0 }]
  const table = id === 'I' ? I_KICKS : JLSTZ_KICKS
  return table[`${from}>${to}`] ?? [{ x: 0, y: 0 }]
}
